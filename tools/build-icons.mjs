// Generates public/js/icons.js from simple-icons (CC0) and lucide-static (ISC).
// Run: npm i --no-save simple-icons lucide-static && node tools/build-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const si = require('simple-icons');
const lucideDir = path.dirname(require.resolve('lucide-static/package.json')) + '/icons';
const brands = ['python','javascript','html5','react','git','docker','nodedotjs','kaggle','khanacademy','coursera','w3schools','mdnwebdocs','figma','googleanalytics','jira','atlassian','googlecloud','googlesheets','roadmapdotsh','hubspot','google','googlechrome','facebook','apple','github','typescript','linux','postgresql','tensorflow','numpy','pandas','openai','notion','slack'];
const glyphs = ['flask-conical','brain','chart-column','code','palette','compass','shield','megaphone','monitor','server','database','cloud','clipboard-list','microscope','pen-line','sigma','pi','binary','search','users','message-square','briefcase','file-text','accessibility','book-open','graduation-cap','globe','trophy','flame','target','timer','check','x','log-in','log-out','user','lock','mail','sparkles','circle-check','external-link','moon','sun','lightbulb','rocket','list-checks','chart-line','star','play','award','trending-up','shield-check','mouse-pointer-click','test-tube','house','settings','layout-dashboard','clock','calendar-days','chart-pie','chart-no-axes-column','eye','eye-off','user-round','key-round','save','refresh-cw','trash-2','download','shuffle','sliders-horizontal','circle-help','list-todo','book-check','square-pen','arrow-right','info'];
const out = { brand: {}, glyph: {} };
for (const b of brands) {
  const k = 'si' + b[0].toUpperCase() + b.slice(1);
  const key = Object.keys(si).find((x) => x.toLowerCase() === 'si' + b);
  if (!key) { console.error('missing brand', b); continue; }
  out.brand[b] = { t: si[key].title, h: si[key].hex, d: si[key].path };
}
for (const g of glyphs) {
  const f = path.join(lucideDir, g + '.svg');
  if (!fs.existsSync(f)) { console.error('missing glyph', g); continue; }
  const svg = fs.readFileSync(f, 'utf8');
  out.glyph[g] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').replace(/\s+/g, ' ').trim();
}
const js = `// GENERATED by tools/build-icons.mjs. Brand marks: simple-icons (CC0). Glyphs: Lucide (ISC).
// Brand logos are trademarks of their owners and are shown only to identify the technology or service.
(function (g) {
  const B = ${JSON.stringify(out.brand)};
  const G = ${JSON.stringify(out.glyph)};
  const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  // icon('brand:python') or icon('glyph:code') -> inline SVG inside a white chip so any brand colour is readable.
  function icon(ref, size, label) {
    const [kind, name] = String(ref || 'glyph:book-open').split(':');
    const s = size || 28;
    let inner;
    if (kind === 'brand' && B[name]) {
      inner = '<svg viewBox="0 0 24 24" width="' + Math.round(s * 0.62) + '" height="' + Math.round(s * 0.62) + '" role="img" aria-label="' + esc(label || B[name].t) + '"><path fill="#' + B[name].h + '" d="' + B[name].d + '"/></svg>';
    } else if (name === 'microsoft') {
      inner = '<svg viewBox="0 0 24 24" width="' + Math.round(s * 0.62) + '" height="' + Math.round(s * 0.62) + '" role="img" aria-label="Microsoft"><path fill="#F25022" d="M1 1h10.5v10.5H1z"/><path fill="#7FBA00" d="M12.5 1H23v10.5H12.5z"/><path fill="#00A4EF" d="M1 12.5h10.5V23H1z"/><path fill="#FFB900" d="M12.5 12.5H23V23H12.5z"/></svg>';
    } else {
      const gl = G[name] || G['book-open'];
      inner = '<svg viewBox="0 0 24 24" width="' + Math.round(s * 0.58) + '" height="' + Math.round(s * 0.58) + '" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"' + (label ? ' role="img" aria-label="' + esc(label) + '"' : ' aria-hidden="true"') + '>' + gl + '</svg>';
    }
    const brand = kind === 'brand' || name === 'microsoft';
    return '<span class="logo' + (brand ? ' brand' : '') + '" style="width:' + s + 'px;height:' + s + 'px">' + inner + '</span>';
  }
  // Small raw glyph for buttons/labels (inherits text colour).
  function glyph(name, size) {
    return '<svg class="gl" viewBox="0 0 24 24" width="' + (size || 16) + '" height="' + (size || 16) + '" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' + (G[name] || '') + '</svg>';
  }
  const HOSTS = [['w3schools.com','brand:w3schools'],['kaggle.com','brand:kaggle'],['khanacademy.org','brand:khanacademy'],['coursera.org','brand:coursera'],['developer.mozilla.org','brand:mdnwebdocs'],['roadmap.sh','brand:roadmapdotsh'],['tryhackme.com','glyph:shield-check'],['hubspot.com','brand:hubspot'],['atlassian.com','brand:atlassian'],['react.dev','brand:react'],['docker.com','brand:docker'],['figma.com','brand:figma'],['skillshop.withgoogle.com','brand:google'],['developers.google.com','brand:google'],['web.dev','brand:googlechrome'],['netacad.com','glyph:globe'],['python.org','brand:python'],['cs50.harvard.edu','glyph:graduation-cap'],['hbs.edu','glyph:graduation-cap'],['w3.org','glyph:globe']];
  function forUrl(url) {
    try { const h = new URL(url).hostname.replace(/^www\\./, ''); const m = HOSTS.find((x) => h === x[0] || h.endsWith('.' + x[0])); return m ? m[1] : 'glyph:book-open'; } catch (e) { return 'glyph:book-open'; }
  }
  g.OrbitIcons = { icon, glyph, forUrl };
})(window);
`;
fs.writeFileSync(new URL('../public/js/icons.js', import.meta.url), js);
console.log('wrote icons.js', js.length, 'bytes; brands', Object.keys(out.brand).length, 'glyphs', Object.keys(out.glyph).length);
